-- Run once in Supabase SQL Editor. Authentication identities live in auth.users.
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null default 'guest' check (role in ('admin','manager','guest')),
  email text unique not null,
  created_at timestamptz not null default now()
);
create table if not exists public.hotels (
  id bigint generated by default as identity primary key,
  name text not null, location text not null, description text, image text,
  manager_id bigint references public.users(id) on delete set null,
  rating numeric(2,1) default 4.5 check (rating between 0 and 5),
  created_at timestamptz not null default now()
);
create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  hotel_id bigint not null references public.hotels(id) on delete cascade,
  room_number text not null, room_type text not null, price numeric(12,2) not null check(price >= 0),
  available boolean not null default true, image text, amenities text,
  unique(hotel_id, room_number)
);
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  guest_id bigint not null references public.users(id) on delete cascade,
  room_id bigint not null references public.rooms(id) on delete cascade,
  hotel_id bigint not null references public.hotels(id) on delete cascade,
  check_in date not null, check_out date not null,
  status text not null default 'Booked' check(status in ('Booked','Confirmed','Completed','Cancelled')),
  created_at timestamptz not null default now(), check(check_out > check_in)
);
create table if not exists public.cancellation_requests (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings(id) on delete cascade,
  guest_id bigint not null references public.users(id) on delete cascade,
  hotel_id bigint not null references public.hotels(id) on delete cascade,
  reason text, status text not null default 'Pending' check(status in ('Pending','Approved','Rejected')),
  manager_note text, created_at timestamptz not null default now(), reviewed_at timestamptz
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null, message text not null, is_read boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists idx_rooms_hotel on public.rooms(hotel_id);
create index if not exists idx_bookings_guest on public.bookings(guest_id);
create index if not exists idx_hotels_manager on public.hotels(manager_id);
create index if not exists idx_notifications_user on public.notifications(user_id, created_at desc);

-- Flask is the trusted server boundary. Block direct anon/authenticated access to app tables.
alter table public.users enable row level security;
alter table public.hotels enable row level security;
alter table public.rooms enable row level security;
alter table public.bookings enable row level security;
alter table public.cancellation_requests enable row level security;
alter table public.notifications enable row level security;
